#!/usr/bin/env python3
"""Generate App/Italiano/DesignSystem/Tokens.swift from design/tokens.json (docs/07: keep the two in sync).

Usage: python3 scripts/gen-tokens.py           # write Tokens.swift
       python3 scripts/gen-tokens.py --check   # exit 1 if Tokens.swift is stale (run by make lint-guards)

The generated file imports Foundation only (plain values), so it also compiles on Linux; the SwiftUI mapping
(dynamic light/dark colours, fonts) lives in the hand-written DesignSystem/Tokens+SwiftUI.swift.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
OUT = ROOT / "App" / "Italiano" / "DesignSystem" / "Tokens.swift"


def ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", name)


def num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def generate(tokens: dict) -> str:
    colors = tokens["color"]
    names = list(colors["light"].keys())
    if list(colors["dark"].keys()) != names:
        raise SystemExit("tokens.json: light and dark palettes must list the same colours in the same order")
    out = [
        "// GENERATED by scripts/gen-tokens.py from design/tokens.json. Do not edit by hand:",
        "// change tokens.json, run `python3 scripts/gen-tokens.py`, and `make lint-guards` checks they match.",
        "import Foundation",
        "",
        "/// One colour palette (light or dark) as 0xRRGGBB values (docs/07, ADR-21).",
        "struct Palette: Sendable, Equatable {",
    ]
    out += [f"    let {ident(n)}: UInt32" for n in names]
    out += ["}", "", "/// Libro design tokens (design/tokens.json).", "enum Tokens {"]
    for mode in ("light", "dark"):
        out.append(f"    static let {mode} = Palette(")
        for i, n in enumerate(names):
            sep = "," if i < len(names) - 1 else ""
            out.append(f"        {ident(n)}: 0x{colors[mode][n].lstrip('#').upper()}{sep}")
        out.append("    )")
    out.append("")
    out.append("    enum FontFamily {")
    out.append(f'        static let italian = "{tokens["font"]["italian"]}"')
    out.append(f'        static let ui = "{tokens["font"]["ui"]}"')
    out.append("        static let files = [")
    out += [f'            "{Path(f).name}",' for f in tokens["font"]["files"]]
    out.append("        ]")
    out.append("    }")
    out.append("")
    out.append("    /// Type scale: every style scales with Dynamic Type (`relativeTo`) and with display.textScale.")
    out.append("    enum TypeScale {")
    for name, s in tokens["type"].items():
        if name.startswith("$"):
            continue
        family = "italian" if s["font"] == "italian" else "ui"
        line = s.get("lineHeight")
        out.append(f"        static let {ident(name)} = TypeStyle(")
        out.append(
            f"            family: .{family}, size: {num(s['size'])}, weight: {s['weight']}, "
            f"lineHeight: {num(line) if line is not None else 'nil'},"
        )
        out.append(f'            italic: {"true" if s.get("italic") else "false"}, relativeTo: .{s["relativeTo"]})')
    out.append("    }")
    for group in ("space", "radius", "border"):
        out.append("")
        out.append(f"    enum {group.capitalize()} {{")
        for k, v in tokens[group].items():
            out.append(f"        static let {ident(k)}: Double = {num(v)}")
        out.append("    }")
    out.append("")
    out.append("    enum Size {")
    for k, v in tokens["size"].items():
        if isinstance(v, dict):
            for sk, sv in v.items():
                out.append(f"        static let {ident(k)}{sk[0].upper()}{ident(sk[1:])}: Double = {num(sv)}")
        else:
            out.append(f"        static let {ident(k)}: Double = {num(v)}")
    out.append("    }")
    out.append("")
    out.append("    enum Motion {")
    for k, v in tokens["motion"].items():
        if isinstance(v, (int, float)):
            out.append(f"        static let {ident(k)}: Double = {num(v)}")
    out.append("    }")
    out.append("")
    out.append("    enum MascotSizes {")
    out.append("        static let all: [Double] = [" + ", ".join(num(x) for x in tokens["mascot"]["sizes"]) + "]")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("struct TypeStyle: Sendable, Equatable {")
    out.append("    enum Family: Sendable { case italian, ui }")
    out.append("    enum TextStyle: Sendable {")
    out.append("        case largeTitle, title, title2, title3, headline, body, callout, footnote, caption")
    out.append("    }")
    out.append("    let family: Family")
    out.append("    let size: Double")
    out.append("    let weight: Int")
    out.append("    let lineHeight: Double?")
    out.append("    let italic: Bool")
    out.append("    let relativeTo: TextStyle")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = generate(json.loads(SRC.read_text(encoding="utf-8")))
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/gen-tokens.py", file=sys.stderr)
            return 1
        print("tokens in sync")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
